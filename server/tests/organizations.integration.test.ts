import 'dotenv/config';
import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import test from 'node:test';
import mysql from 'mysql2/promise';
import jwt from 'jsonwebtoken';

test('平级组织支持迁移、维护、员工归属与使用中保护', async () => {
  const database = `yunqi_org_${randomBytes(8).toString('hex')}`;
  const conn = await mysql.createConnection({ host: process.env.MYSQL_HOST || '127.0.0.1', port: Number(process.env.MYSQL_PORT || 3306), user: process.env.MYSQL_USER || 'root', password: process.env.MYSQL_PASSWORD || '' });
  let created = false; let closePool: (() => Promise<void>) | undefined; let closeServer: (() => Promise<void>) | undefined;
  try {
    await conn.query(`CREATE DATABASE \`${database}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci`); created = true;
    process.env.MYSQL_DATABASE = database;
    const pool = await import('../src/shared/db/pool'); closePool = pool.closePool; await pool.ensureSchema();
    await (await import('../src/shared/db/seed')).seedDatabase();
    await pool.execute("INSERT INTO departments (id, parent_id, name) VALUES ('D02', 'D00', '旧模拟部门')");
    await pool.execute("UPDATE employees SET dept_id = 'D02' WHERE id = 'U001'");
    await pool.execute("INSERT INTO hr_employee_transitions (employee_id, change_type, effective_date, before_json, after_json, status, created_by, created_at) VALUES ('U001', 'transfer', '2025-01-01', JSON_OBJECT('deptId', 'D02'), JSON_OBJECT('deptId', 'D00'), 'submitted', 1, NOW())");
    await (await import('../src/admin/employees/adminEmployeeService')).backfillEmployeeJobCategories();
    await (await import('../src/domains/employees/jobTitleService')).backfillJobTitles();
    const org = await import('../src/domains/employees/organizationService');
    await org.migrateOrganizations();
    assert.equal((await pool.queryRows<{ name: string }>("SELECT name FROM legacy_department_names WHERE id = 'D02'"))[0].name, '旧模拟部门');
    await (await import('../src/admin/admin-accounts/adminAuthService')).ensureDefaultAdmin();
    const { config } = await import('../src/config');
    const server = (await import('../src/app')).createApp().listen(0, '127.0.0.1'); await new Promise<void>(resolve => server.once('listening', resolve));
    closeServer = () => new Promise<void>((resolve, reject) => server.close(err => err ? reject(err) : resolve()));
    const addr = server.address(); assert.ok(addr && typeof addr !== 'string');
    const token = jwt.sign({ typ: 'admin', role: 'super_admin' }, config.jwt.secret, { subject: '1' });
    const call = async (path: string, method = 'GET', body?: unknown) => { const r = await fetch(`http://127.0.0.1:${addr.port}/api${path}`, { method, headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) }); return { status: r.status, body: await r.json() as { data?: any; message?: string } }; };
    assert.deepEqual((await call('/admin/organizations')).body.data, []);
    assert.equal((await call('/admin/organizations', 'POST', { name: '未分配' })).status, 409);
    const employee = (await call('/admin/employees/U001')).body.data;
    assert.equal(employee.deptId, 'D00');
    assert.equal(employee.position, '研发员');
    const history = await call('/admin/hr/employee-transitions?employeeId=U001');
    assert.equal(history.body.data[0].legacyOrganizationNames.D02, '旧模拟部门');
    assert.equal((await call(`/admin/hr/employee-transitions/${history.body.data[0].id}/cancel`, 'POST', {})).status, 400);
    assert.equal((await call('/admin/employees/U001')).body.data.deptId, 'D00');
    const added = await call('/admin/organizations', 'POST', { name: '研发中心' }); assert.equal(added.status, 200);
    assert.equal((await call('/admin/organizations', 'POST', { name: '研发中心' })).status, 409);
    const id = added.body.data.id;
    assert.equal((await call(`/admin/organizations/${id}`, 'PUT', { name: '产品研发' })).status, 200);
    const input = { ...employee, deptId: id, gender: employee.gender || undefined, leaderId: employee.leaderId || undefined };
    assert.equal((await call('/admin/employees/U001', 'PUT', input)).status, 200);
    const titles = (await call('/admin/job-titles')).body.data;
    assert.ok(titles.flatMap((title: any) => title.employees).some((row: any) => row.id === 'U001' && row.deptId === id && row.deptName === '产品研发'));
    assert.equal((await call(`/admin/organizations/${id}`, 'DELETE')).status, 409);
    await org.migrateOrganizations();
    assert.equal((await call('/admin/employees/U001')).body.data.deptId, id);
    assert.equal((await call('/admin/employees/U001', 'PUT', { ...input, deptId: 'D00' })).status, 200);
    assert.equal((await call(`/admin/organizations/${id}`, 'DELETE')).status, 200);
  } finally { if (closeServer) await closeServer(); if (closePool) await closePool(); if (created) await conn.query(`DROP DATABASE \`${database}\``); await conn.end(); }
});
