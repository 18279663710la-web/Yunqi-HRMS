import 'dotenv/config';
import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { createServer } from 'node:http';
import { mkdtemp, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import mysql from 'mysql2/promise';

test('真实校验通过的报销单异步生成建议，并只向指定审批人展示', async () => {
  const database = `yunqi_ai_test_${randomBytes(8).toString('hex')}`;
  const uploadDir = await mkdtemp(path.join(os.tmpdir(), 'yunqi-ai-test-'));
  process.env.UPLOAD_DIR = uploadDir;
  let modelCalls = 0;
  let modelInput = '';
  let modelFails = false;
  let interruptStream = false;
  let releaseModelStream: (() => void) | undefined;
  const model = createServer((req, res) => {
    let raw = '';
    req.on('data', (chunk) => { raw += chunk; });
    req.on('end', () => {
      modelCalls += 1;
      modelInput = raw;
      if (modelFails) { res.statusCode = 503; res.end(); return; }
      if (JSON.parse(raw).stream) {
        res.setHeader('Content-Type', 'text/event-stream');
        const emit = (content: string) => res.write(`data: ${JSON.stringify({ choices: [{ delta: { content } }] })}\n\n`);
        emit('{"reason":"未提供');
        if (interruptStream) { res.end(); return; }
        releaseModelStream = () => { releaseModelStream = undefined; emit('行程单","recommendation":"reject","ruleIds":["R1"],"rule":"差旅报销需要行程证明","missingAttachments":["行程单"],"attachmentIssues":[]}'); res.end('data: [DONE]\n\n'); };
        return;
      }
      res.setHeader('Content-Type', 'application/json');
      res.end(JSON.stringify({ choices: [{ message: { content: JSON.stringify({ recommendation: 'reject', reason: '未提供行程单', ruleIds: ['R1'], rule: '差旅报销需要行程证明', missingAttachments: ['行程单'] }) } }] }));
    });
  }).listen(0, '127.0.0.1');
  await new Promise<void>((resolve) => model.once('listening', resolve));
  const modelAddress = model.address(); assert.ok(modelAddress && typeof modelAddress !== 'string');
  process.env.EXPENSE_AI_DRIVER = 'local';
  process.env.EXPENSE_AI_BASE_URL = `http://127.0.0.1:${modelAddress.port}`;
  process.env.EXPENSE_AI_MODEL = 'test-model';
  process.env.VERIFY_DRIVER = 'tencent';
  process.env.TENCENTCLOUD_SECRET_ID = 'test-only';
  process.env.TENCENTCLOUD_SECRET_KEY = 'test-only';
  const { ocr } = await import('tencentcloud-sdk-nodejs-ocr');
  const prototype = ocr.v20181119.Client.prototype as any;
  const originalVerify = prototype.VatInvoiceVerifyNew;
  let valid = false;
  prototype.VatInvoiceVerifyNew = async (request: any) => ({ Invoice: { Number: request.InvoiceNo, IsAbandoned: valid ? 'N' : 'Y', RedLetterInvoiceMark: false, AmountWithTax: request.Amount, AmountWithoutTax: request.Amount } });
  const conn = await mysql.createConnection({ host: process.env.MYSQL_HOST || '127.0.0.1', port: Number(process.env.MYSQL_PORT || 3306), user: process.env.MYSQL_USER || 'root', password: process.env.MYSQL_PASSWORD || '' });
  let closePool: (() => Promise<void>) | undefined;
  let closeServer: (() => Promise<void>) | undefined;
  let created = false;
  try {
    await conn.query(`CREATE DATABASE \`${database}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci`); created = true;
    process.env.MYSQL_DATABASE = database;
    const pool = await import('../src/shared/db/pool'); closePool = pool.closePool;
    await pool.ensureSchema();
    await (await import('../src/shared/db/seed')).seedDatabase();
    await (await import('../src/admin/employees/adminEmployeeService')).backfillEmployeeJobCategories();
    await conn.query(`INSERT INTO \`${database}\`.approval_approvers (type, employee_id, updated_by, updated_at) VALUES ('expense','U005',1,NOW())`);
    await conn.query(`INSERT INTO \`${database}\`.approval_rules (type, content, updated_by, updated_at) VALUES ('expense','差旅费须提供行程单',1,NOW())`);
    const { issueTokens } = await import('../src/miniprogram/auth/authService');
    const server = (await import('../src/app')).createApp().listen(0, '127.0.0.1');
    await new Promise<void>((resolve) => server.once('listening', resolve));
    closeServer = () => new Promise<void>((resolve, reject) => server.close((err) => err ? reject(err) : resolve()));
    const address = server.address(); assert.ok(address && typeof address !== 'string');
    const base = `http://127.0.0.1:${address.port}/api`;
    const applicant = issueTokens('U001').accessToken;
    const reviewer = issueTokens('U005').accessToken;
    async function request(url: string, token: string, method = 'GET', body?: unknown) {
      const response = await fetch(base + url, { method, headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) });
      return { status: response.status, body: await response.json() as { data?: any } };
    }
    const invoice = { id: 'ai-invoice', invoiceCode: '', invoiceNumber: '12345678901234567890', invoiceDate: '2026-10-28', invoiceType: '普通发票', amount: 10, taxAmount: 0, totalAmount: 10 };
    const formData = new FormData();
    formData.append('file', new Blob([new Uint8Array([137, 80, 78, 71, 13, 10, 26, 10])], { type: 'image/png' }), 'contract.png');
    const uploaded = await fetch(base + '/invoices/image', { method: 'POST', headers: { Authorization: `Bearer ${applicant}` }, body: formData });
    assert.equal(uploaded.status, 200);
    const uploadData = await uploaded.json() as { data: { fileUrl: string } };
    const payload = { type: 'expense', title: '差旅报销', form: [{ label: '用途', value: '出差' }], invoices: [invoice], attachments: [{ name: '合同', fileID: uploadData.data.fileUrl }] };
    assert.equal((await request('/approvals/expense-precheck', applicant, 'POST', payload)).status, 400, '验伪失败时不触发预审');
    assert.equal((await request('/approvals', applicant, 'POST', payload)).status, 400);
    const worker = await import('../src/domains/approvals/expenseAiService');
    await worker.processExpenseAiQueue(); assert.equal(modelCalls, 0);
    valid = true;
    await conn.query(`UPDATE \`${database}\`.approval_rules SET content = '' WHERE type = 'expense'`);
    assert.equal((await request('/approvals/expense-precheck', applicant, 'POST', payload)).body.data.status, 'no_rules');
    assert.equal(modelCalls, 0, '没有规则时不调用模型');
    await conn.query(`UPDATE \`${database}\`.approval_rules SET content = '差旅费须提供行程单' WHERE type = 'expense'`);
    const precheck = await request('/approvals/expense-precheck', applicant, 'POST', payload);
    assert.equal(precheck.status, 200);
    assert.equal(precheck.body.data.advice.recommendation, 'reject');
    assert.deepEqual(precheck.body.data.advice.missingAttachments, ['行程单']);
    assert.match(modelInput, /data:image\/png;base64/);
    const streamResponse = await fetch(base + '/approvals/expense-precheck/stream', { method: 'POST', headers: { Authorization: `Bearer ${applicant}`, 'Content-Type': 'application/json' }, body: JSON.stringify(payload) });
    assert.equal(streamResponse.status, 200);
    assert.match(streamResponse.headers.get('content-type') || '', /text\/event-stream/);
    const reader = streamResponse.body!.getReader();
    const decoder = new TextDecoder();
    const first = await reader.read();
    const progress = decoder.decode(first.value);
    assert.match(progress, /"type":"progress"/, '模型尚未结束时应收到增量内容');
    assert.ok(releaseModelStream, '模型流仍在等待');
    releaseModelStream();
    let rest = '';
    for (;;) { const next = await reader.read(); if (next.done) break; rest += decoder.decode(next.value, { stream: true }); }
    assert.match(rest, /"type":"result"/);
    assert.match(rest, /"recommendation":"reject"/);
    const [beforeSubmit] = await conn.query(`SELECT COUNT(*) AS count FROM \`${database}\`.approvals WHERE title = ?`, [payload.title]);
    assert.equal(Number((beforeSubmit as Array<{ count: number }>)[0].count), 0, '预审不能提交审批单');
    assert.equal((await request('/approvals/expense-precheck', reviewer, 'POST', payload)).status, 400, '预审不能读取他人的附件');
    const createdApproval = await request('/approvals', applicant, 'POST', payload);
    assert.equal(createdApproval.status, 200);
    const id = createdApproval.body.data.id;
    assert.equal(createdApproval.body.data.aiAdvice, null);
    assert.equal((await request(`/approvals/${id}`, reviewer)).body.data.aiAdvice.status, 'queued');
    await conn.query(`UPDATE \`${database}\`.approval_rules SET content = '新规则' WHERE type = 'expense'`);
    assert.equal((await request('/approvals', applicant, 'POST', { ...payload, invoices: [{ ...invoice, id: 'duplicate' }] })).status, 400);
    assert.equal((await request(`/approvals/${id}/action`, reviewer, 'POST', { action: 'approve' })).body.data.ok, true);
    await worker.processExpenseAiQueue();
    assert.equal(modelCalls, 3);
    assert.match(modelInput, /差旅费须提供行程单/);
    assert.match(modelInput, /data:image\/png;base64/);
    const detail = (await request(`/approvals/${id}`, reviewer)).body.data;
    assert.equal(detail.status, 'approved');
    assert.equal(detail.aiAdvice.status, 'completed');
    assert.equal(detail.attachments[0].name, '合同');
    assert.equal(detail.aiAdvice.advice.recommendation, 'reject');
    assert.equal(detail.aiAdvice.advice.rule, '差旅费须提供行程单');
    assert.deepEqual(detail.aiAdvice.advice.missingAttachments, ['行程单']);
    assert.equal((await request(`/approvals/${id}`, applicant)).body.data.aiAdvice, null);
    interruptStream = true;
    const brokenStream = await fetch(base + '/approvals/expense-precheck/stream', { method: 'POST', headers: { Authorization: `Bearer ${applicant}`, 'Content-Type': 'application/json' }, body: JSON.stringify({ ...payload, invoices: [{ ...invoice, id: 'broken', invoiceNumber: '12345678901234567894' }] }) });
    const brokenResult = await brokenStream.text();
    assert.match(brokenResult, /"status":"failed"/, '模型流中断时不能把半截内容当作完整建议');
    modelFails = true;
    const foreignAttachment = await request('/approvals', reviewer, 'POST', { ...payload, invoices: [{ ...invoice, id: 'foreign-invoice', invoiceNumber: '12345678901234567892' }] });
    assert.equal(foreignAttachment.status, 400, '不能提交其他账号上传的补充材料');
    const unavailable = await request('/approvals/expense-precheck', applicant, 'POST', { ...payload, invoices: [{ ...invoice, id: 'ai-preview-failure', invoiceNumber: '12345678901234567893' }] });
    assert.equal(unavailable.body.data.status, 'failed', '模型不可用时预审返回失败状态而非阻止人工提交');
    const second = await request('/approvals', applicant, 'POST', { ...payload, invoices: [{ ...invoice, id: 'ai-second', invoiceNumber: '12345678901234567891' }] });
    assert.equal(second.status, 200);
    for (let i = 0; i < 3; i += 1) await worker.processExpenseAiQueue();
    assert.equal((await request(`/approvals/${second.body.data.id}`, reviewer)).body.data.aiAdvice.status, 'failed');
    assert.equal((await request(`/approvals/${second.body.data.id}/action`, reviewer, 'POST', { action: 'approve' })).body.data.ok, true);
  } finally {
    if (releaseModelStream) releaseModelStream();
    prototype.VatInvoiceVerifyNew = originalVerify;
    if (closeServer) await closeServer();
    if (closePool) await closePool();
    if (created) await conn.query(`DROP DATABASE \`${database}\``);
    await conn.end();
    await rm(uploadDir, { recursive: true, force: true });
    await new Promise<void>((resolve) => model.close(() => resolve()));
  }
});
