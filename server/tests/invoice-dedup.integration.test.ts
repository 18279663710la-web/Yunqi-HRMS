import 'dotenv/config';
import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import test from 'node:test';
import mysql from 'mysql2/promise';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';

test('报销在提交和查验前按发票身份查重，并发提交只允许一个成功', async () => {
  const database = `yunqi_invoice_test_${randomBytes(8).toString('hex')}`;
  const uploadDir = await mkdtemp(path.join(os.tmpdir(), 'yunqi-invoice-test-'));
  assert.equal(path.resolve(path.dirname(uploadDir)), path.resolve(os.tmpdir()));
  process.env.UPLOAD_DIR = uploadDir;
  process.env.VERIFY_DRIVER = 'tencent';
  process.env.TENCENTCLOUD_SECRET_ID = 'test-only';
  process.env.TENCENTCLOUD_SECRET_KEY = 'test-only';
  const { ocr } = await import('tencentcloud-sdk-nodejs-ocr');
  const prototype = ocr.v20181119.Client.prototype as any;
  const originalVerify = prototype.VatInvoiceVerifyNew;
  let invoiceAbandoned = true;
  let apiCalls = 0;
  prototype.VatInvoiceVerifyNew = async (request: any) => { apiCalls++; return { Invoice: { Number: request.InvoiceNo, IsAbandoned: invoiceAbandoned ? 'Y' : 'N', RedLetterInvoiceMark: false, AmountWithTax: request.Amount || '10.00', AmountWithoutTax: '10.00' } }; };
  const connection = await mysql.createConnection({ host: process.env.MYSQL_HOST || '127.0.0.1', port: Number(process.env.MYSQL_PORT || 3306), user: process.env.MYSQL_USER || 'root', password: process.env.MYSQL_PASSWORD || '' });
  let created = false;
  let closePool: (() => Promise<void>) | undefined;
  let closeServer: (() => Promise<void>) | undefined;
  try {
    await connection.query(`CREATE DATABASE \`${database}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci`);
    created = true;
    process.env.MYSQL_DATABASE = database;
    const pool = await import('../src/shared/db/pool');
    closePool = pool.closePool;
    await pool.ensureSchema();
    const { seedDatabase } = await import('../src/shared/db/seed');
    await seedDatabase();
    const { backfillEmployeeJobCategories } = await import('../src/admin/employees/adminEmployeeService');
    await backfillEmployeeJobCategories();
    await connection.query(`INSERT INTO \`${database}\`.approval_approvers (type, employee_id, updated_by, updated_at) VALUES ('expense', 'U005', 1, NOW())`);
    const { issueTokens } = await import('../src/miniprogram/auth/authService');
    const { createApp } = await import('../src/app');
    const server = createApp().listen(0, '127.0.0.1');
    await new Promise<void>((resolve) => server.once('listening', resolve));
    closeServer = () => new Promise<void>((resolve, reject) => server.close((err) => err ? reject(err) : resolve()));
    const address = server.address();
    assert.ok(address && typeof address !== 'string');
    const base = `http://127.0.0.1:${address.port}/api`;
    const worker = issueTokens('U001').accessToken;
    const leader = issueTokens('U005').accessToken;
    const form = new FormData();
    const bytes = new Uint8Array([137, 80, 78, 71, 13, 10, 26, 10]);
    form.append('file', new Blob([bytes], { type: 'image/png' }), 'invoice.png');
    const uploadResponse = await fetch(base + '/invoices/image', { method: 'POST', headers: { Authorization: `Bearer ${worker}` }, body: form });
    assert.equal(uploadResponse.status, 200);
    const uploaded = await uploadResponse.json() as { data: { fileUrl: string; invoice?: unknown } };
    assert.match(uploaded.data.fileUrl, /^\/uploads\/[\w.-]+\.png$/);
    assert.equal(uploaded.data.invoice, undefined);
    assert.deepEqual(await readFile(path.join(uploadDir, path.basename(uploaded.data.fileUrl))), Buffer.from(bytes));
    async function request(path: string, method = 'GET', body?: unknown, token = worker) {
      const response = await fetch(base + path, { method, headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) });
      return { status: response.status, payload: await response.json() as { data?: any; message?: string } };
    }
    const invoice = { id: 'inv-a', invoiceCode: '', invoiceNumber: '12345678901234567890', invoiceDate: '2026-10-28', invoiceType: '普通发票', checkCode: '123456', amount: 10, taxAmount: 0, totalAmount: 10 };
    const expense = (items: unknown[]) => ({ type: 'expense', title: '报销', invoices: items });
    assert.equal((await request('/approvals', 'POST', expense([]))).status, 400);
    assert.equal((await request('/approvals', 'POST', expense([{ ...invoice, isMock: true }]))).status, 400);
    const incomplete = await request('/invoices/duplicate', 'POST', { invoice: { invoiceNumber: '12345678' } });
    assert.equal(incomplete.status, 400);
    assert.equal((await request('/approvals', 'POST', expense([invoice, { ...invoice, id: 'inv-b', invoiceCode: '044031900111' }]))).status, 400);
    const abnormal = await request('/approvals', 'POST', expense([invoice]));
    assert.equal(abnormal.status, 400);
    assert.match(abnormal.payload.message || '', /作废|红冲/);
    invoiceAbandoned = false;
    const before = apiCalls;
    assert.equal((await request('/invoices/verify', 'POST', { invoice })).payload.data.status, 'valid');
    const first = await request('/approvals', 'POST', expense([invoice]));
    assert.equal(first.status, 200);
    assert.equal(apiCalls, before + 1, '短时间内相同发票查验结果应复用');
    const dup = await request('/invoices/duplicate', 'POST', { invoice: { ...invoice, invoiceCode: '044031900111' } });
    assert.equal(dup.payload.data.blocking, true);
    assert.equal((await request('/approvals', 'POST', expense([{ ...invoice, id: 'inv-c' }]))).status, 400);
    const verification = await request('/invoices/verify', 'POST', { invoice, options: { skipDuplicateCheck: true, excludeApprovalId: first.payload.data.id } });
    assert.equal(verification.payload.data.status, 'duplicated');
    assert.equal((await request(`/approvals/${first.payload.data.id}/cancel`, 'POST', {})).payload.data.ok, true);
    const afterCancel = await request('/approvals', 'POST', expense([{ ...invoice, id: 'inv-after-cancel' }]));
    assert.equal(afterCancel.status, 200);
    assert.equal((await request(`/approvals/${afterCancel.payload.data.id}/action`, 'POST', { action: 'reject', comment: '退回' }, leader)).payload.data.ok, true);
    const afterReject = await request('/approvals', 'POST', expense([{ ...invoice, id: 'inv-after-reject' }]));
    assert.equal(afterReject.status, 200);
    assert.equal((await request(`/approvals/${afterReject.payload.data.id}/action`, 'POST', { action: 'approve', comment: '通过' }, leader)).payload.data.ok, true);
    assert.equal((await request('/approvals', 'POST', expense([{ ...invoice, id: 'inv-after-approval' }]))).status, 400);
    const traditional = { ...invoice, id: 'traditional', invoiceType: '增值税电子普通发票', invoiceCode: '044031900111', invoiceNumber: '08812453' };
    assert.equal((await request('/approvals', 'POST', expense([traditional]))).status, 200);
    assert.equal((await request('/approvals', 'POST', expense([{ ...traditional, id: 'traditional-again' }]))).status, 400);
    assert.equal((await request('/approvals', 'POST', expense([{ ...traditional, id: 'traditional-other-code', invoiceCode: '044031900112' }]))).status, 200);
    const raceNo = '12345678901234567891';
    const race = await Promise.all(Array.from({ length: 4 }, (_, i) => request('/approvals', 'POST', expense([{ ...invoice, invoiceNumber: raceNo, id: `race-${i}` }]))));
    assert.equal(race.filter((result) => result.status === 200).length, 1);
    assert.equal(race.filter((result) => result.status === 400).length, 3);
    const [occupied] = await connection.query(`SELECT COUNT(*) AS total FROM \`${database}\`.invoices i JOIN \`${database}\`.approvals a ON a.id=i.approval_id WHERE i.invoice_number=? AND a.status IN ('pending','approved')`, [raceNo]);
    assert.equal(Number((occupied as Array<{ total: number }>)[0].total), 1);
  } finally {
    prototype.VatInvoiceVerifyNew = originalVerify;
    if (closeServer) await closeServer();
    if (closePool) await closePool();
    if (created) await connection.query(`DROP DATABASE \`${database}\``);
    await connection.end();
    await rm(uploadDir, { recursive: true, force: true });
  }
});
