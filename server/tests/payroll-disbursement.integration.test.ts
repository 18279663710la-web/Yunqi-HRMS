import 'dotenv/config';
import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import test from 'node:test';
import mysql from 'mysql2/promise';
import jwt from 'jsonwebtoken';

test('工资批次发放生成快照并锁定补充项', async () => {
  const database = `yunqi_disbursement_${randomBytes(8).toString('hex')}`;
  const conn = await mysql.createConnection({ host: process.env.MYSQL_HOST || '127.0.0.1', port: Number(process.env.MYSQL_PORT || 3306), user: process.env.MYSQL_USER || 'root', password: process.env.MYSQL_PASSWORD || '' });
  let created = false; let closePool: (() => Promise<void>) | undefined; let closeServer: (() => Promise<void>) | undefined;
  try {
    await conn.query(`CREATE DATABASE \`${database}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci`); created = true;
    process.env.MYSQL_DATABASE = database;
    const pool = await import('../src/shared/db/pool'); closePool = pool.closePool; await pool.ensureSchema();
    await (await import('../src/shared/db/seed')).seedDatabase(); await (await import('../src/admin/admin-accounts/adminAuthService')).ensureDefaultAdmin();
    const { config } = await import('../src/config');
    const server = (await import('../src/app')).createApp().listen(0, '127.0.0.1'); await new Promise<void>(resolve => server.once('listening', resolve));
    closeServer = () => new Promise<void>((resolve, reject) => server.close(err => err ? reject(err) : resolve()));
    const address = server.address(); assert.ok(address && typeof address !== 'string');
    const admin = await pool.queryOne<{ id: number }>("SELECT id FROM admins WHERE role = 'super_admin' LIMIT 1"); assert.ok(admin);
    const token = jwt.sign({ typ: 'admin', role: 'super_admin' }, config.jwt.secret, { subject: String(admin.id) });
    const call = async (path: string, method = 'GET', body?: unknown) => {
      const response = await fetch(`http://127.0.0.1:${address.port}/api/admin/hr${path}`, { method, headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) });
      return { status: response.status, body: await response.json() as { data?: any } };
    };
    await conn.query(`INSERT INTO \`${database}\`.hr_payroll_records (employee_id, payroll_month, amount, note, created_at) VALUES ('U001', '2026-02', 100.25, '历史记录', NOW())`);
    assert.ok([401, 404].includes((await call('/payroll', 'POST', { employeeId: 'U005', month: '2026-03', amount: 1, note: '' })).status));
    assert.ok([401, 404].includes((await call('/payroll/batch', 'POST', { batchId: 1 })).status));
    assert.ok([401, 404].includes((await call('/payroll')).status));
    await conn.query(`INSERT INTO \`${database}\`.hr_payroll_batches (payroll_month, status, created_at) VALUES ('2026-01', 'draft', NOW()), ('2026-02', 'reviewed', NOW())`);
    const batches = await call('/payroll-batches?month=2026-02');
    assert.equal(batches.status, 200);
    assert.deepEqual(batches.body.data.map((batch: any) => [batch.month, batch.status]), [['2026-02', 'reviewed']]);
    assert.equal((await call('/payroll-batches?month=2026-13')).status, 400);
    assert.equal((await call('/payroll-batches')).body.data.length, 2);
    const reviewedId = batches.body.data[0].id;
    const draftId = (await call('/payroll-batches?month=2026-01')).body.data[0].id;
    await pool.execute("INSERT INTO hr_payroll_batch_items (batch_id, employee_id, gross, deductions, net, note) VALUES (?, 'U001', 4400, 200, 4200, ''), (?, 'U005', 3700, 0, 3700, '')", [reviewedId, reviewedId]);
    const initial = await call(`/payroll-batches/${reviewedId}/disbursement`);
    assert.equal(initial.status, 200);
    assert.deepEqual(initial.body.data.rows.map((row: any) => row.net), [4400, 3700]);
    assert.equal((await call(`/payroll-batches/${draftId}/disbursement/fields`, 'POST', { name: '奖金', category: 'income', required: true, displaySetting: 'none' })).status, 400);
    const add = async (name: string, category: string) => call(`/payroll-batches/${reviewedId}/disbursement/fields`, 'POST', { name, category, required: true, displaySetting: 'none' });
    const income = await add('奖金', 'income');
    const deduction = await add('代扣', 'deduction');
    const info = await add('备注金额', 'info');
    assert.equal(income.status, 200); assert.equal(deduction.status, 200); assert.equal(info.status, 200);
    assert.notEqual((await add('奖金', 'income')).status, 200);
    const fieldId = income.body.data.id;
    const itemId = initial.body.data.rows[0].itemId;
    const update = (id: number, value: number, revision = 0) => call(`/payroll-batches/${reviewedId}/disbursement/items/${itemId}/fields/${id}`, 'PUT', { value, revision });
    assert.equal((await update(fieldId, 100.25)).status, 200);
    assert.equal((await update(deduction.body.data.id, 30.10)).status, 200);
    assert.equal((await update(info.body.data.id, 999)).status, 200);
    assert.equal((await update(fieldId, 5)).status, 409);
    assert.equal((await update(fieldId, -1, 1)).status, 400);
    assert.equal((await update(fieldId, 1.001, 1)).status, 400);
    assert.equal((await call(`/payroll-batches/${reviewedId}/disbursement/items/${itemId}/fields/99999`, 'PUT', { value: 1, revision: 0 })).status, 404);
    assert.notEqual((await add('应发', 'income')).status, 200);
    const concurrent = await Promise.all([update(info.body.data.id, 1000, 1), update(info.body.data.id, 2000, 1)]);
    assert.deepEqual(concurrent.map(result => result.status).sort(), [200, 409]);
    await conn.query(`INSERT INTO \`${database}\`.admins (username, password_hash, name, role, status, created_at) VALUES ('disbursement_hr', 'x', 'HR', 'hr_admin', 1, NOW())`);
    const hr = await pool.queryOne<{ id: number }>("SELECT id FROM admins WHERE username = 'disbursement_hr'"); assert.ok(hr);
    const hrToken = jwt.sign({ typ: 'admin', role: 'hr_admin' }, config.jwt.secret, { subject: String(hr.id) });
    const forbidden = await fetch(`http://127.0.0.1:${address.port}/api/admin/hr/payroll-batches/${reviewedId}/disbursement`, { headers: { Authorization: `Bearer ${hrToken}` } });
    assert.equal(forbidden.status, 403);
    const saved = (await call(`/payroll-batches/${reviewedId}/disbursement`)).body.data;
    assert.deepEqual(saved.rows.map((row: any) => row.net), [4470.15, 3700]);
    assert.equal(saved.rows[0].values.find((value: any) => value.fieldId === fieldId).value, 100.25);
    const original = (await call(`/payroll-batches/${reviewedId}/items`)).body.data[0];
    assert.equal(original.gross, 4400); assert.equal(original.net, 4200);
    assert.equal((await call(`/payroll-batches/${draftId}/disbursement/issue`, 'POST', { revision: saved.revision })).status, 400);
    assert.equal((await call(`/payroll-batches/${reviewedId}/disbursement/issue`, 'POST', { revision: 'stale' })).status, 409);
    const originalName = saved.snapshot.items[0].name;
    await pool.execute("UPDATE employees SET name = '并发修改' WHERE id = 'U001'");
    assert.equal((await call(`/payroll-batches/${reviewedId}/disbursement/issue`, 'POST', { revision: saved.revision })).status, 409);
    await pool.execute("UPDATE employees SET name = ? WHERE id = 'U001'", [originalName]);
    const pdf = Buffer.from('%PDF-1.4\n1 0 obj\n<<>>\nendobj\n%%EOF\n').toString('base64');
    const sendPayslip = (id: number, item: number, file = pdf) => call(`/payroll-batches/${id}/disbursement/items/${item}/payslip`, 'POST', { pdf: file });
    assert.equal((await sendPayslip(reviewedId, itemId)).status, 400);
    const issuing = await Promise.all([call(`/payroll-batches/${reviewedId}/disbursement/issue`, 'POST', { revision: saved.revision }), call(`/payroll-batches/${reviewedId}/disbursement/issue`, 'POST', { revision: saved.revision })]);
    assert.deepEqual(issuing.map(result => result.status).sort(), [200, 409]);
    const issued = issuing.find(result => result.status === 200)!;
    assert.ok(issued.body.data.id);
    assert.equal((await call(`/payroll-batches/${reviewedId}/disbursement/issue`, 'POST', { revision: saved.revision })).status, 409);
    assert.equal((await add('新补充', 'income')).status, 409);
    assert.equal((await update(fieldId, 200, 1)).status, 409);
    const recordsV2 = await call('/payroll-disbursement-records');
    assert.equal(recordsV2.body.data.length, 1);
    assert.deepEqual([recordsV2.body.data[0].month, Number(recordsV2.body.data[0].grossTotal), Number(recordsV2.body.data[0].netTotal), recordsV2.body.data[0].note], ['2026-02', 8100, 8170.15, '']);
    const snapshot = (await call(`/payroll-disbursement-records/${issued.body.data.id}`)).body.data;
    assert.equal(snapshot.batch.month, '2026-02');
    assert.equal(snapshot.items.length, 2);
    assert.equal(snapshot.disbursement.fields.length, 3);
    assert.equal(snapshot.disbursement.rows[0].net, 4470.15);
    await pool.execute("UPDATE employees SET name = '后续名称' WHERE id = 'U001'");
    const historical = (await call(`/payroll-disbursement-records/${issued.body.data.id}`)).body.data;
    assert.equal(historical.items[0].name, snapshot.items[0].name);
    const lockedView = (await call(`/payroll-batches/${reviewedId}/disbursement`)).body.data;
    assert.equal(lockedView.issued, true);
    assert.equal(lockedView.snapshot.items[0].name, originalName);
    const { issueTokens } = await import('../src/miniprogram/auth/authService');
    const userToken = issueTokens('U001').accessToken;
    const otherToken = issueTokens('U005').accessToken;
    const employeeCall = async (path: string, employeeToken: string, method = 'GET', body?: unknown) => fetch(`http://127.0.0.1:${address.port}/api/payslips${path}`, { method, headers: { Authorization: `Bearer ${employeeToken}`, 'Content-Type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) });
    assert.equal((await sendPayslip(reviewedId, itemId, Buffer.from('invalid').toString('base64'))).status, 400);
    assert.equal((await sendPayslip(reviewedId, 999999)).status, 404);
    const sent = await sendPayslip(reviewedId, itemId);
    assert.equal(sent.status, 200);
    const id = sent.body.data.id;
    assert.equal(sent.body.data.revision, 1);
    assert.deepEqual((await call(`/payroll-batches/${reviewedId}/disbursement`)).body.data.sentItemIds, [itemId]);
    let list = await (await employeeCall('', userToken)).json() as any;
    assert.equal(list.data.length, 1);
    assert.equal(list.data[0].month, '2026-02');
    assert.equal(list.data[0].read, false);
    assert.equal((await (await employeeCall('', otherToken)).json() as any).data.length, 0);
    assert.equal((await employeeCall(`/${id}/pdf`, otherToken)).status, 404);
    assert.equal((await employeeCall(`/${id}/read`, otherToken, 'POST', { revision: 1 })).status, 404);
    const file = await employeeCall(`/${id}/pdf`, userToken);
    assert.equal(file.status, 200); assert.match(file.headers.get('content-type') || '', /application\/pdf/);
    assert.equal(Buffer.from(await file.arrayBuffer()).toString('base64'), pdf);
    assert.equal((await employeeCall(`/${id}/read`, userToken, 'POST', { revision: 1 })).status, 200);
    list = await (await employeeCall('', userToken)).json() as any;
    assert.equal(list.data[0].read, true);
    const resent = await sendPayslip(reviewedId, itemId, Buffer.from('%PDF-1.4 different content %%EOF').toString('base64'));
    assert.equal(resent.status, 200);
    assert.equal(resent.body.data.id, id);
    assert.equal(resent.body.data.revision, 2);
    assert.equal((await employeeCall(`/${id}/read`, userToken, 'POST', { revision: 1 })).status, 409);
    assert.equal(Buffer.from(await (await employeeCall(`/${id}/pdf`, userToken)).arrayBuffer()).toString('base64'), pdf);
    assert.equal((await fetch(`http://127.0.0.1:${address.port}/api/payslips/${id}/pdf`)).status, 401);
    assert.equal((await (await employeeCall('', userToken)).json() as any).data[0].read, false);
    const hrSend = await fetch(`http://127.0.0.1:${address.port}/api/admin/hr/payroll-batches/${reviewedId}/disbursement/items/${itemId}/payslip`, { method: 'POST', headers: { Authorization: `Bearer ${hrToken}`, 'Content-Type': 'application/json' }, body: JSON.stringify({ pdf }) });
    assert.equal(hrSend.status, 403);

  } finally {
    if (closeServer) await closeServer(); if (closePool) await closePool();
    if (created) await conn.query(`DROP DATABASE \`${database}\``); await conn.end();
  }
});
